5. 小角龙呼出巨王棘龙：发动小角龙被效果破坏送墓的效果，从牌组特殊召唤巨王棘龙。
6. 进化药召唤传导恐兽：发动究极进化药，除外墓地小角龙与手牌灰流丽，满足一只恐龙族＋一只非恐龙族，特殊召唤牌组究极传导恐兽。
7. 确认恐龙压制场面：保留窃蛋龙、珠玉兽、巨王棘龙和3500攻击的究极传导恐兽。传导恐兽在对方回合可破坏手牌或场上一只怪兽，把对方怪兽盖成里侧守备。
