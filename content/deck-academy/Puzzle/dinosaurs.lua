经典-恐龙
窃蛋龙＋珠玉兽＋巨王棘龙＋究极传导恐兽，演示恐龙破坏触发与进化药的双种族费用。
1. 窃蛋龙检索混种恐龙：通常召唤食魂窃蛋龙，选择加入手牌，把牌组的幻创之混种恐龙检索到手。
