--[[message
竞技-星辰
巨蟹魔检索宝瓶魔，利用手牌融合、素材盖卡和罗睺的牌组融合建立双融合怪兽，并回收宝瓶魔准备对方回合融合。
1. 巨蟹魔检索宝瓶魔：通常召唤星辰枪手 巨蟹魔，发动召唤成功效果检索星辰炮手 宝瓶魔。手牌中的星辰龙 摩羯龙（Pan）先保留作为融合素材。
2. 丢弃宝瓶魔发动融合：在主要阶段发动宝瓶魔的快速效果，丢弃宝瓶魔作为代价。用场上巨蟹魔与手牌摩羯龙作为融合素材，融合召唤星辰法宫 狮子宝瓶龙魔（Gulamel）。
3. 素材效果分别盖卡：巨蟹魔作为融合素材进墓地后盖放罗睺星辰；摩羯龙作为融合素材进墓地后盖放星辰的刺毒（Sting）。练习中对方场上无怪兽时，不要选择破坏自己刚做出的融合怪兽。
4. 罗睺继续牌组融合：罗睺是通常魔法，盖放当回合即可发动。用牌组的星辰龙 天蝎龙（Mululu）和手牌灰流丽作为素材，融合召唤星辰爪龙 巨蟹摩羯龙魔（Arthalion），同时保留狮子宝瓶龙魔在场。
5. 回收宝瓶魔并盖角：巨蟹摩羯龙魔的融合召唤效果选择墓地宝瓶魔回手，因为本次用了1只手牌素材所以可选择至多1只怪兽。天蝎龙的融合素材效果盖放星辰的裂角（Horn）；没有对方表侧怪兽时跳过可选无效。
6. 保留对方回合融合：终场保留两只融合怪兽、刺毒与裂角，以及回手的宝瓶魔。宝瓶魔本回合已用过，但对方回合次数重置后可再次丢弃发动融合；新手牌和场上素材要满足目标融合怪兽的要求。
