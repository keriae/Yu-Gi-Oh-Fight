--[[message
竞技-巳剑
两种巳剑降临模式接续，利用被解放的小怪回收与正确仪式召唤的大怪自我苏生建立双仪式怪兽及反制陷阱。
1. 羽斩展示与麁正检索：展示手牌天羽羽斩之巳剑，发动一场决斗一次的效果，特殊召唤牌组巳剑之尊 麁正，接着把麁正解放。发动麁正被解放的效果检索天丛云之巳剑。
