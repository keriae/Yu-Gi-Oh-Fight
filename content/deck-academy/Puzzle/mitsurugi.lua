3. 先使用手牌仪式模式：发动巳剑降临，选择从手牌仪式召唤的模式。用场上的佐士（4星）和牌组的草那艺（4星）作为两只素材，仪式召唤手牌天丛云（8星）。
4. 草那艺回收降临：发动草那艺被解放后的效果，选择刚进入墓地的巳剑降临加入手牌。对方场上没有怪兽时，天丛云的全体破坏效果不需要发动。
5. 再使用牌组仪式模式：再次发动巳剑降临，这次选择从牌组仪式召唤的另一模式。解放已经正确仪式召唤的场上天丛云（8星），仪式召唤牌组中的另一张天羽羽斩（8星）；展示过的那张羽斩仍在手牌。
6. 天丛云检索并回场：发动被解放的天丛云效果，检索巳剑大祓，并继续选择特殊召唤天丛云自身。它先前经过正确仪式召唤，因此此处可从墓地回场。盖放巳剑大祓。
7. 确认双怪兽与反制：终场羽斩降低对方怪兽攻击，天丛云可要求对方丢1手牌或无效其效果，大祓可解放5星以上爬虫类无效并破坏。大祓与天丛云被解放后的效果各有次数限制，合理分配应对。
