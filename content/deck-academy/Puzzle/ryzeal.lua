--[[message
竞技-雷火沸动
围绕4阶超量建立交界机与爆震机的双重干扰。内燃单卡启动，练习检索、去素材、苏生与素材补充的资源闭环。
1. 通常召唤内燃：通常召唤内燃雷火沸动机，发动召唤成功效果，从牌组特殊召唤剑式阴极雷火沸动机。
2. 检索并特殊召唤外燃：剑式的效果检索外燃雷火沸动机。把额外牌组的分体论聚合员送去墓地，按外燃的召唤手续从手牌特殊召唤外燃；其效果检索节式阳极雷火沸动机（Node）。
3. 超量油电双动机：使用场上的内燃与剑式，超量召唤雷火沸动油电双动机。外燃留在怪兽区；目前墓地没有可吸收的雷火怪兽时，不发动双动机的召唤成功加素材效果。
4. 去除两个素材并检索：发动双动机的主要阶段效果，去除其两个素材，把雷火沸动交界机和雷火沸动机插电（Plugin）加入手牌。
5. 交界机与插电补充资源：发动交界机。发动雷火沸动机插电，苏生墓地的内燃；继续选择双动机，把另一张牌组中的节式阳极雷火沸动机作为素材放到双动机下方。这里加素材来自牌组。
6. 制作死旋爆震机：使用外燃与刚苏生的内燃，超量召唤雷火沸动死旋爆震机。发动其召唤成功效果，把墓地的分体论聚合员作为素材。
7. 确认可用干扰：终场为有1素材的双动机、通常有3素材的爆震机与交界机。交界机可在对方怪兽效果处理时去素材无效该效果；爆震机响应对方发动而破坏卡片。保留素材，不要把所有素材提前花光。
]]
